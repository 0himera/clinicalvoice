package diagnostics

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"errors"
	"io"
	"log/slog"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"syscall"
	"time"
)

var ErrExpired = errors.New("transcript record has expired")

type envelope struct {
	Version int    `json:"v"`
	Created string `json:"created"`
	Expires string `json:"expires"`
	Data    string `json:"data"`
}

func (e envelope) aad() []byte {
	return []byte("tochka-transcript/v1\x00" + e.Created + "\x00" + e.Expires)
}

// Encrypted stores authenticated JSONL records in bounded hourly files. Nonces
// are generated by the standard library, and expiry is authenticated with data.
type Encrypted struct {
	mu        sync.Mutex
	dir       string
	aead      cipher.AEAD
	retention time.Duration
	now       func() time.Time
	file      *File
	bucket    string
	closed    bool
}

func CreateKey(path string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		return err
	}
	info, err := os.Lstat(filepath.Dir(path))
	if err != nil {
		return err
	}
	if !info.IsDir() || info.Mode().Perm()&0077 != 0 {
		return errors.New("transcript key directory must be private (0700)")
	}
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return err
	}
	defer file.Close()
	key := make([]byte, 32)
	defer func() {
		for i := range key {
			key[i] = 0
		}
	}()
	if _, err = rand.Read(key); err != nil {
		return err
	}
	if _, err = file.Write(key); err != nil {
		return err
	}
	return file.Sync()
}

func LoadCipher(keyPath string) (cipher.AEAD, error) {
	file, err := os.OpenFile(keyPath, os.O_RDONLY|syscall.O_NOFOLLOW, 0)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	info, err := file.Stat()
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() || info.Mode().Perm()&0077 != 0 {
		return nil, errors.New("transcript key must be a private regular file (0600)")
	}
	key, err := io.ReadAll(io.LimitReader(file, 33))
	if err != nil {
		return nil, err
	}
	defer func() {
		for i := range key {
			key[i] = 0
		}
	}()
	if len(key) != 32 {
		return nil, errors.New("transcript key must contain exactly 32 bytes")
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}
	return cipher.NewGCMWithRandomNonce(block)
}

func OpenEncrypted(directory, keyPath string, retention time.Duration) (*Encrypted, error) {
	if retention < time.Hour || retention > 24*time.Hour {
		return nil, errors.New("transcript retention must be between 1 and 24 hours")
	}
	dir, err := filepath.Abs(directory)
	if err != nil {
		return nil, err
	}
	key, err := filepath.Abs(keyPath)
	if err != nil {
		return nil, err
	}
	if relative, err := filepath.Rel(dir, key); err == nil && relative != ".." && !strings.HasPrefix(relative, ".."+string(os.PathSeparator)) {
		return nil, errors.New("transcript key must be stored outside the transcript directory")
	}
	aead, err := LoadCipher(key)
	if err != nil {
		return nil, err
	}
	if err = os.MkdirAll(dir, 0700); err != nil {
		return nil, err
	}
	info, err := os.Lstat(dir)
	if err != nil || !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return nil, errors.New("transcript directory must be a real directory")
	}
	if err = os.Chmod(dir, 0700); err != nil {
		return nil, err
	}
	w := &Encrypted{dir: dir, aead: aead, retention: retention, now: time.Now}
	if err = w.Prune(); err != nil {
		return nil, err
	}
	return w, nil
}

func (w *Encrypted) Write(data []byte) (count int, resultErr error) {
	defer func() {
		if resultErr != nil {
			slog.Error("encrypted transcript write failed", "error_kind", "storage_error")
		}
	}()
	w.mu.Lock()
	defer w.mu.Unlock()
	if w.closed {
		return 0, os.ErrClosed
	}
	now := w.now().UTC()
	start := now.Truncate(time.Hour)
	bucket := "transcript-" + start.Format("20060102T15")
	if w.file == nil || bucket != w.bucket {
		if w.file != nil {
			if err := w.file.Close(); err != nil {
				return 0, err
			}
		}
		file, err := Open(w.dir, bucket)
		if err != nil {
			return 0, err
		}
		file.limit = 1 << 20
		w.file, w.bucket = file, bucket
	}
	e := envelope{Version: 1, Created: now.Format(time.RFC3339Nano), Expires: start.Add(w.retention).Format(time.RFC3339Nano)}
	e.Data = base64.StdEncoding.EncodeToString(w.aead.Seal(nil, nil, data, e.aad()))
	encoded, err := json.Marshal(e)
	if err != nil {
		return 0, err
	}
	if _, err = w.file.Write(append(encoded, '\n')); err != nil {
		return 0, err
	}
	return len(data), nil
}

func Decrypt(aead cipher.AEAD, line []byte, now time.Time) ([]byte, error) {
	var e envelope
	if err := json.Unmarshal(line, &e); err != nil || e.Version != 1 {
		return nil, errors.New("invalid transcript envelope")
	}
	ciphertext, err := base64.StdEncoding.DecodeString(e.Data)
	if err != nil {
		return nil, errors.New("invalid transcript encoding")
	}
	data, err := aead.Open(nil, nil, ciphertext, e.aad())
	if err != nil {
		return nil, errors.New("transcript authentication failed")
	}
	expires, err := time.Parse(time.RFC3339Nano, e.Expires)
	if err != nil {
		return nil, errors.New("invalid transcript expiry")
	}
	if !now.Before(expires) {
		return nil, ErrExpired
	}
	return data, nil
}

func (w *Encrypted) Prune() error {
	w.mu.Lock()
	defer w.mu.Unlock()
	entries, err := os.ReadDir(w.dir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		name := strings.TrimSuffix(entry.Name(), ".1")
		if !strings.HasPrefix(name, "transcript-") || !strings.HasSuffix(name, ".jsonl") {
			continue
		}
		stamp := strings.TrimSuffix(strings.TrimPrefix(name, "transcript-"), ".jsonl")
		start, err := time.Parse("20060102T15", stamp)
		if err != nil || w.now().Before(start.Add(w.retention)) {
			continue
		}
		if w.file != nil && strings.TrimSuffix(filepath.Base(w.file.path), ".jsonl") == strings.TrimSuffix(name, ".jsonl") {
			if err := w.file.Close(); err != nil {
				return err
			}
			w.file = nil
		}
		if entry.Type().IsRegular() {
			if err := os.Remove(filepath.Join(w.dir, entry.Name())); err != nil {
				return err
			}
		}
	}
	return nil
}

func (w *Encrypted) Run(ctxDone <-chan struct{}) {
	ticker := time.NewTicker(time.Minute)
	defer ticker.Stop()
	for {
		select {
		case <-ctxDone:
			return
		case <-ticker.C:
			if err := w.Prune(); err != nil {
				slog.Error("transcript retention cleanup failed", "error_kind", "storage_error")
			}
		}
	}
}

func (w *Encrypted) Close() error {
	w.mu.Lock()
	defer w.mu.Unlock()
	w.closed = true
	if w.file != nil {
		return w.file.Close()
	}
	return nil
}

var _ io.WriteCloser = (*Encrypted)(nil)
