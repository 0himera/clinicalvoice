package dialogue

import (
	"strings"
	"testing"
)

func TestFAQKnowledgeBaseCoverage(t *testing.T) {
	cases := []struct {
		query       string
		expectedSub string
	}{
		{"Сколько стоит приём терапевта?", "бесплатны"},
		{"У вас есть платные услуги?", "Платные медицинские услуги"},
		{"Какой прейскурант цен?", "бесплатны"},
		{"До скольки можно вызвать врача на дом?", "с восьми до четырнадцати часов"},
		{"Как вызвать врача на дом?", "с восьми до четырнадцати часов"},
		{"Где пройти флюорографию?", "108"},
		{"Как сделать рентген?", "108"},
		{"Как открыть больничный лист?", "лечащего врача"},
		{"Где получить справку в бассейн?", "терапевтом"},
		{"Нужно ли сдавать кровь натощак?", "натощак"},
		{"Как подготовиться к УЗИ брюшной полости?", "шесть–восемь часов"},
		{"Где сделать прививку от гриппа?", "105"},
		{"Как пройти диспансеризацию?", "105"},
		{"Когда будет готов общий анализ крови?", "один рабочий день"},
		{"Когда готова гистология?", "десять–четырнадцать"},
		{"Какой адрес у поликлиники?", "Центральная, дом семь"},
		{"Какие документы взять с собой?", "паспорт и полис ОМС"},
		{"Какой у вас график работы?", "семи тридцати до двадцати"},
	}

	for _, tc := range cases {
		ans, ok := FAQ(tc.query)
		if !ok {
			t.Errorf("FAQ failed to match query: %q", tc.query)
			continue
		}
		if !strings.Contains(ans, tc.expectedSub) {
			t.Errorf("FAQ(%q) = %q; expected to contain %q", tc.query, ans, tc.expectedSub)
		}
	}
}
