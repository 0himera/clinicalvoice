package dialogue

import "strings"

// FAQ returns approved facts, not generated medical advice. Analysis readiness is
// a reference answer: the hackathon MIS has no laboratory-status API.
func FAQ(text string) (string, bool) {
	s := normalized(text)
	switch {
	case containsAny(s, "результат", "готовност", "готовы анализ", "когда анализ") || (containsAny(s, "готов", "когда", "через сколько") && containsAny(s, "анализ", "исследован", "глюкоз", "холестерин", "гистолог", "цитолог", "посев", "пцр", "гормон", "биохим")):
		term := "Срок зависит от исследования. Общий анализ крови и мочи — один рабочий день."
		switch {
		case containsAny(s, "гистолог"):
			term = "Гистология обычно готова через десять–четырнадцать рабочих дней."
		case containsAny(s, "цитолог"):
			term = "Цитология обычно готова через семь–десять рабочих дней."
		case containsAny(s, "посев"):
			term = "Бактериологический посев обычно готов через пять–семь рабочих дней."
		case containsAny(s, "гормон"):
			term = "Гормональные исследования обычно готовы через три–пять рабочих дней."
		case containsAny(s, "пцр"):
			term = "ПЦР обычно готова через два–три рабочих дня."
		case containsAny(s, "биохим", "глюкоз", "коагул", "гликирован"):
			term = "Эти исследования обычно готовы через один–два рабочих дня."
		}
		return term + " Получить результат можно через Госуслуги, лечащего врача или окно номер три по будням с двенадцати до девятнадцати.", true
	case containsAny(s, "стоимост", "сколько стоит", "платно", "платные услуг", "платный приём", "платный терапевт", "прайс", "прейскурант", "цена", "цены"):
		return "Приём врачей и базовые анализы по полису ОМС бесплатны. Платные медицинские услуги оказываются по договору в окне номер пять.", true
	case containsAny(s, "до скольки вызов", "со скольки вызов", "график вызова", "время вызова", "часы вызова") ||
		((containsAny(s, "как", "когда", "можно ли", "условия") || strings.Contains(s, "?")) && containsAny(s, "вызов врача", "вызвать врача", "вызов на дом", "вызвать на дом")):
		return "Заявки на вызов врача на дом принимаются по будням с восьми до четырнадцати часов по телефону или через регистратуру.", true
	case containsAny(s, "флюорограф", "рентген", "маммограф", "флюшка"):
		return "Кабинет флюорографии и рентгена номер 108 работает по будням с восьми до шестнадцати часов в порядке живой очереди, при себе необходимо иметь паспорт.", true
	case containsAny(s, "больничн", "открыть больничный", "закрыть больничный", "продлить больничный", "справку в бассейн", "справка в бассейн", "справка в лагерь", "справка для гибдд", "справка от врача") ||
		(containsAny(s, "справк", "больничн") && containsAny(s, "как", "где", "получить", "оформить", "взять", "открыть", "закрыть")):
		return "Оформление, продление и закрытие больничных листов осуществляется на приёме у лечащего врача. Справки и направления выдаются терапевтом или в окне номер два.", true
	case (containsAny(s, "подготов", "натощак", "как сдавать", "как готовиться") && containsAny(s, "анализ", "кров", "моч", "узи", "исследован")) ||
		containsAny(s, "натощак или нет", "сдавать натощак", "кушать перед", "есть перед анализом"):
		return "Кровь для большинства анализов сдаётся строго натощак: за двенадцать часов исключите жирную пищу, чай и кофе. Для УЗИ брюшной полости не принимайте пищу за шесть–восемь часов до исследования.", true
	case containsAny(s, "прививк", "вакцинац", "диспансеризац", "профосмотр"):
		return "Кабинет профилактики и вакцинации номер 105 работает по будням с восьми до шестнадцати часов. Приём проводится в порядке живой очереди после осмотра у терапевта.", true
	case containsAny(s, "забор крови", "сдать кровь", "процедурн"):
		return "Забор крови: по будням с семи тридцати до десяти тридцати, в субботу с девяти до одиннадцати.", true
	case containsAny(s, "адрес", "где находит") || (word(s, "где") && strings.Contains(s, "находит")):
		return "Улица Центральная, дом семь. Вход в детское отделение — с торца здания.", true
	case containsAny(s, "прикреп"):
		return "Для прикрепления нужны паспорт, полис ОМС и СНИЛС. Обратитесь в регистратуру или подайте заявление через Госуслуги.", true
	case containsAny(s, "что взять", "документ"):
		return "Возьмите паспорт и полис ОМС. Для ребёнка — свидетельство о рождении, полис и паспорт представителя.", true
	case clinicHoursQuestion(s):
		if bare := strings.Trim(s, " .,!?—-"); bare == "в субботу" || bare == "а в субботу" || bare == "по субботам" || bare == "суббота" {
			return "В субботу поликлиника работает с девяти до пятнадцати. Принимают дежурные терапевт и педиатр.", true
		}
		return "Будни — с семи тридцати до двадцати. Суббота — с девяти до пятнадцати, дежурные терапевт и педиатр. Воскресенье — выходной.", true
	}
	return "", false
}

func clinicHoursQuestion(s string) bool {
	switch strings.Trim(s, " .,!?—-") {
	case "в субботу", "а в субботу", "по субботам", "суббота":
		return true
	}
	return containsAny(s, "график работы поликлиник", "режим работы", "работаете", "до скольки работает", "со скольки работает", "график работы?", "часы работы", "время работы", "дни работы", "ваш график", "открываетесь", "закрываетесь", "вы открыты", "когда откры", "когда закры", "поликлиника открыта", "поликлиника работает")
}

func scheduleQuestion(s string) bool {
	return clinicHoursQuestion(s) || containsAny(s, "график", "расписани", "когда принима", "когда работа", "в какие дни", "по каким дням", "дни приема", "до скольки", "со скольки", "со скольк")
}

func isMedicalQuestion(s string) bool {
	return containsAny(s, "что выпить", "что мне выпить", "лекарств", "препарат", "таблетк", "что принять", "как принимать", "чем лечить", "как лечить", "дозировк", "поставьте диагноз", "какой диагноз", "расшифруйте анализ", "оцените анализ", "какой холестерин", "какой у меня холестерин", "значение анализ", "результаты хорошие", "результаты плохие")
}
